#!/usr/bin/env python3
"""Convert FlashGBX's GBA flash cart profiles into web/flashcart_profiles.js.

Usage: python3 tools/import_flashgbx.py <FlashGBX checkout> [output.js]

FlashGBX (https://github.com/Lesserkuma/FlashGBX, GPL-3.0) describes each
flash cart in a FlashGBX/config/fc_AGB_*.txt file: its flash IDs, sector
layout and the command words for erasing and writing. The web app uses them
as data. Profiles that need hardware a GBA doesn't have (cart power cycling)
or that are not flash carts (read protections) are left out.
"""
import glob
import json
import os
import re
import sys

SKIP_COMMAND_SETS = {"3DMEMORY", "GBAMP", "VASTFAME"}


def load(path):
    text = open(path, encoding="utf-8-sig").read()
    text = re.sub(r"(?m)//.*$", "", text)
    text = re.sub(r"\b0x[0-9A-Fa-f]+\b", lambda m: str(int(m.group(0), 16)), text)
    text = re.sub(r",(\s*[\]}])", r"\1", text)
    return json.loads(text)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    root = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(__file__), "..", "web", "flashcart_profiles.js")
    config_dir = os.path.join(root, "FlashGBX", "config")
    version = "unknown"
    try:
        with open(os.path.join(root, "pyproject.toml"), encoding="utf-8") as f:
            m = re.search(r'(?m)^version\s*=\s*"([^"]+)"', f.read())
            if m:
                version = m.group(1)
    except OSError:
        pass

    profiles = []
    for path in sorted(glob.glob(os.path.join(config_dir, "fc_AGB_*.txt"))):
        d = load(path)
        if d.get("type", "").upper() != "AGB":
            continue
        if str(d.get("command_set", "")).upper() in SKIP_COMMAND_SETS:
            continue
        if d.get("power_cycle"):
            continue
        d.pop("type", None)
        d.pop("voltage", None)
        d = {"id": os.path.basename(path)[3:-4], **d}
        profiles.append(d)

    lines = [
        "/**",
        " * GBA flash cart profiles, generated by tools/import_flashgbx.py from",
        f" * FlashGBX {version} by Lesserkuma (https://github.com/Lesserkuma/FlashGBX,",
        " * GPL-3.0). Do not edit by hand: re-run the script against a newer FlashGBX.",
        " */",
        "",
        '"use strict";',
        "",
        "const FLASHCART_PROFILES = [",
    ]
    for p in profiles:
        lines.append("    " + json.dumps(p, separators=(",", ":"), ensure_ascii=False) + ",")
    lines += [
        "];",
        "",
        'if (typeof window !== "undefined") window.FLASHCART_PROFILES = FLASHCART_PROFILES;',
        'if (typeof module !== "undefined" && module.exports) module.exports = { FLASHCART_PROFILES };',
        "",
    ]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(profiles)} profiles to {out}")


if __name__ == "__main__":
    main()
