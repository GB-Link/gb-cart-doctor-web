#!/usr/bin/env python3
"""Convert FlashGBX's flash cart profiles into web/flashcart_profiles.js (GBA)
and web/gb_flashcart_profiles.js (GB/GBC).

Usage: python3 tools/import_flashgbx.py <FlashGBX checkout> [output.js [gb_output.js]]

FlashGBX (https://github.com/Lesserkuma/FlashGBX, GPL-3.0) describes each
flash cart in a FlashGBX/config/fc_AGB_*.txt or fc_DMG_*.txt file: its flash
IDs, sector layout and the commands for erasing and writing. The web app
reads these as data.

Some profiles are left out: carts that need something a GBA or GBC can't do
from inside the console (turning the cart's power off and on, a reset pin,
the cartridge AUDIO pin as the write signal, or a bank switch between a
flash command and its data), and entries that aren't flash carts at all
(copy protections).
"""
import glob
import json
import os
import re
import sys

SKIP_COMMAND_SETS = {"3DMEMORY", "GBAMP", "VASTFAME"}

# GB mappers the GBC payload can't drive: ones that need the cart's power
# turned off and on, or that use their own flash commands.
SKIP_DMG_MBCS = {0x105, 0x201, 0x202, 0x203, 0x204, 0x205}


def load(path):
    text = open(path, encoding="utf-8-sig").read()
    text = re.sub(r"(?m)//.*$", "", text)
    text = re.sub(r"\b0x[0-9A-Fa-f]+\b", lambda m: str(int(m.group(0), 16)), text)
    text = re.sub(r",(\s*[\]}])", r"\1", text)
    return json.loads(text)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    root = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(__file__), "..", "web", "flashcart_profiles.js")
    config_dir = os.path.join(root, "FlashGBX", "config")
    version = "unknown"
    try:
        with open(os.path.join(root, "pyproject.toml"), encoding="utf-8") as f:
            m = re.search(r'(?m)^version\s*=\s*"([^"]+)"', f.read())
            if m:
                version = m.group(1)
    except OSError:
        pass

    profiles = []
    for path in sorted(glob.glob(os.path.join(config_dir, "fc_AGB_*.txt"))):
        d = load(path)
        if d.get("type", "").upper() != "AGB":
            continue
        if str(d.get("command_set", "")).upper() in SKIP_COMMAND_SETS:
            continue
        if d.get("power_cycle"):
            continue
        d.pop("type", None)
        d.pop("voltage", None)
        d = {"id": os.path.basename(path)[3:-4], **d}
        profiles.append(d)

    write_js(out, "GBA", "FLASHCART_PROFILES", profiles, version)

    gb = []
    for path in sorted(glob.glob(os.path.join(config_dir, "fc_DMG_*.txt"))):
        d = load(path)
        if d.get("type", "").upper() != "DMG":
            continue
        if d.get("write_pin") != "WR" or str(d.get("command_set", "")).upper() != "AMD":
            continue
        if d.get("power_cycle") or d.get("pulse_reset_after_write") or d.get("set_audio_high") or \
                d.get("flash_commands_on_bank_1"):
            continue
        if d.get("mbc") in SKIP_DMG_MBCS or "flash_ids_banks" in d:
            continue
        if any(isinstance(i, list) and len(i) > 1 and isinstance(i[1], list) for i in d.get("flash_ids", [])):
            continue
        c = d.get("commands", {})
        if "single_write" not in c or not ("sector_erase" in c or "chip_erase" in c):
            continue
        for k in ("type", "voltage", "voltage_variants", "write_pin"):
            d.pop(k, None)
        gb.append({"id": os.path.basename(path)[3:-4], **d})
    gb_out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(
        os.path.dirname(out), "gb_flashcart_profiles.js")
    write_js(gb_out, "GB/GBC", "GB_FLASHCART_PROFILES", gb, version)


def write_js(out, kind, name, profiles, version):
    lines = [
        "/**",
        f" * {kind} flash cart profiles, generated by tools/import_flashgbx.py from",
        f" * FlashGBX {version} by Lesserkuma (https://github.com/Lesserkuma/FlashGBX,",
        " * GPL-3.0). Do not edit by hand: re-run the script against a newer FlashGBX.",
        " */",
        "",
        '"use strict";',
        "",
        f"const {name} = [",
    ]
    for p in profiles:
        lines.append("    " + json.dumps(p, separators=(",", ":"), ensure_ascii=False) + ",")
    lines += [
        "];",
        "",
        f'if (typeof window !== "undefined") window.{name} = {name};',
        f'if (typeof module !== "undefined" && module.exports) module.exports = {{ {name} }};',
        "",
    ]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(profiles)} profiles to {out}")


if __name__ == "__main__":
    main()
