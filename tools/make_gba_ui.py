#!/usr/bin/env python3
"""Build the GBA dumper's screen graphics as a C header,
source/gba_cart_dumper/source/ui_gfx.h. It holds the same font as the GBC
menu (ASCII 0x20-0x7E, one bit per pixel) and the tiles for the cartridge
icon, the panels, the divider line and the progress bar (4 bits per pixel)."""
import os
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_gbc_ui import font  # noqa: E402

# A GBA cartridge, 24x16 pixels. Colours: 1 outline, 2 body, 3 label,
# 4 grip.
CART = """
........................
.######################.
.#22222222222222222222#.
.#22333333333333333322#.
.#23333333333333333332#.
.#23333333333333333332#.
.#23333333333333333332#.
.#23333333333333333332#.
.#23333333333333333332#.
.#22333333333333333322#.
.#22222222222222222222#.
.#22222222222222222222#.
.#22424242424242424222#.
.#22222222222222222222#.
.######################.
........................
"""

# After the icon's six tiles come these, in this order (see T_* in ui.c).
SOLID = ["11111111"] * 8
LINE = ["........"] * 4 + ["11111111"] + ["........"] * 3


def bar(filled):
    """A progress bar tile with its first `filled` columns done. The bar
    covers rows 1-6: colour 2 for the done part, colour 1 for the rest."""
    row = "2" * filled + "1" * (8 - filled)
    return ["........"] + [row] * 6 + ["........"]


def tile4(rows):
    """Pack an 8x8 tile at 4 bits per pixel. '.' is colour 0, '#' is
    colour 1, a digit is that colour. Each byte holds two pixels, the left
    one in the low four bits."""
    def px(c):
        return 0 if c == "." else 1 if c == "#" else int(c)
    out = bytearray()
    for r in rows:
        for x in range(0, 8, 2):
            out.append(px(r[x]) | px(r[x + 1]) << 4)
    return bytes(out)


def tiles():
    cart = [l for l in CART.split("\n") if l]
    out = b""
    for ty in (0, 8):
        for tx in (0, 8, 16):
            out += tile4([r[tx:tx + 8] for r in cart[ty:ty + 8]])
    out += tile4(SOLID) + tile4(LINE)
    for f in range(9):
        out += tile4(bar(f))
    return out


def c_array(name, data):
    lines = [f"static const u8 {name}[{len(data)}] __attribute__((aligned(4))) = {{"]
    for i in range(0, len(data), 16):
        lines.append("\t" + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


if __name__ == "__main__":
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                        "source", "gba_cart_dumper", "source", "ui_gfx.h")
    with open(path, "w") as f:
        f.write("/* Generated by tools/make_gba_ui.py. */\n")
        f.write("#ifndef UI_GFX_H\n#define UI_GFX_H\n\n")
        f.write(c_array("uiFont", font()) + "\n\n")
        f.write(c_array("uiTiles", tiles()) + "\n\n")
        f.write("#endif\n")
