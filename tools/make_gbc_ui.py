# The font is drawn bold to be easier to read. These letters are drawn bold
# by hand, because simply thickening them would fill in their gaps. Each row
# is 7 columns wide.
BOLD = {
    "M": "##...## ###.### ##.#.## ##.#.## ##...## ##...## ##...## .......",
    "N": ".##..## .###.## .###.## .##.### .##.### .##..## .##..## .......",
    "W": "##...## ##...## ##...## ##.#.## ##.#.## ###.### ##...## .......",
    "m": "....... ....... ###.##. ##.#.## ##.#.## ##.#.## ##.#.## .......",
    "w": "....... ....... ##...## ##.#.## ##.#.## ##.#.## .##.##. .......",
}

# 2bpp tiles, colours 0-3. Tiles 1-4: a cartridge (top left, top right,
# bottom left, bottom right). Tile 5: a divider line.
CART = """
..33333333333...
..311111111133..
..3111111111113.
..3122222222113.
..3122222222113.
..3122222222113.
..3122222222113.
..3122222222113.
..3111111111113.
..3111111111113.
..3111111111113.
..3111111111113.
..3131313131313.
..3111111111113.
..3333333333333.
................
"""
LINE = """
........
........
........
........
11111111
........
........
........
"""


def font():
    rows = [l for l in GLYPHS.split("\n") if l.strip()]
    out = bytearray()
    assert len(rows) == 95
    for code, line in zip(range(0x20, 0x7F), rows):
        bits = line.split()
        if code != 0x20:                    # the space's line has no character
            assert bits.pop(0) == chr(code), line
        assert len(bits) == 8 and all(len(b) == 5 for b in bits), line
        if chr(code) in BOLD:
            for b in BOLD[chr(code)].split():
                out.append(sum(0x80 >> i for i, p in enumerate(b) if p == "#"))
            continue
        for b in bits:
            v = 0
            for i, p in enumerate(b):
                if p == "#":
                    v |= 0x40 >> i          # columns 1-5 of the tile
            out.append(v | v >> 1)          # bold: thicken every stroke
    assert len(out) == 95 * 8
    return bytes(out)


def tile(pix):
    out = bytearray()
    for row in pix:
        lo = hi = 0
        for x, p in enumerate(row):
            c = 0 if p == "." else int(p)
            lo |= (c & 1) << (7 - x)
            hi |= (c >> 1) << (7 - x)
        out += bytes([lo, hi])
    return bytes(out)


def tiles():
    cart = [l for l in CART.split("\n") if l]
    line = [l for l in LINE.split("\n") if l]
    out = b""
    for ty, tx in ((0, 0), (0, 8), (8, 0), (8, 8)):
        out += tile([r[tx:tx + 8] for r in cart[ty:ty + 8]])
    return out + tile(line)


if __name__ == "__main__":
    d = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "source", "gbc_payload")
    with open(os.path.join(d, "ui_font.bin"), "wb") as f:
        f.write(font())
    with open(os.path.join(d, "ui_tiles.bin"), "wb") as f:
        f.write(tiles())
